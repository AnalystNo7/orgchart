/**
 * Бюджеты одного прогона AI-чата.
 *
 * Диагностика таймаута (tasks/ai-context-budget/BRIEF.md) показала: 99.8%
 * времени уходит в модель, и растёт оно вместе с объёмом входа. Поэтому
 * ограничиваем не код, а то, сколько данных попадает в контекст, и оставляем
 * запас, чтобы обрыв был внятным.
 */

/**
 * Держать синхронно с `export const maxDuration` в
 * src/app/api/ai/chat/route.ts: Next читает maxDuration статически, поэтому
 * импортированная константа там не годится — только литерал.
 */
export const AI_ROUTE_MAX_DURATION_SEC = 300;

/**
 * Запас, чтобы таймаут цикла generateText сработал ДО того, как платформа
 * убьёт функцию: успевают уйти SSE-событие error и сохранение диалога.
 */
export const AI_LOOP_SAFETY_MS = 20_000;

/**
 * Потолок суммарного объёма результатов инструментов за один прогон.
 * Результаты остаются в истории сообщений и переотправляются на каждом шаге,
 * поэтому важна именно сумма, а не размер отдельного вызова.
 * Наблюдавшийся провальный прогон набрал ~180 КБ за один шаг.
 */
export const AI_RUN_CONTEXT_BUDGET_BYTES = 120_000;

/**
 * Максимум шагов tool-цикла. До потолка по времени прогоны ни разу не доходили
 * до прежних 10 шагов, но пользователь явно просил не ограничиваться ими:
 * важен доведённый отчёт, а не экономия обращений.
 */
export const AI_MAX_STEPS = 30;

/** Бюджет ОДНОГО вызова модели (шага). Reasoning-шаги легально идут минутами. */
export const AI_STEP_TIMEOUT_MS = 600_000;

/**
 * Максимальная тишина между чанками стрима. Пока токены идут — не срабатывает
 * никогда; мёртвое соединение обрывается за 2 минуты вместо всего бюджета.
 */
export const AI_CHUNK_TIMEOUT_MS = 120_000;

/** Весь цикл, когда активного пресета нет (env-fallback). */
export const AI_DEFAULT_TOTAL_TIMEOUT_MS = 1_800_000;

/**
 * Суммарный объём документов базы знаний, включённых флажком в системный
 * промпт (байты UTF-8). Потолок шлюза — 65 536 Б на один текстовый блок,
 * промпт — один блок, и ~15–20 КБ занимают методическая и техническая
 * части. 45 000 Б ≈ 22 тыс. русских символов (кириллица — 2 байта/символ).
 * Включение сверх бюджета отклоняется на API; молчаливой обрезки нет.
 */
export const AI_KB_PROMPT_BUDGET_BYTES = 45_000;

/**
 * Повторы при retryable-ошибках провайдера: 429 (лимит запросов, занятый
 * слот шлюза «too many concurrent requests»), 529/503 (перегрузка), сетевой
 * обрыв. Считаются ПОВТОРЫ, не попытки: 3 → до 4 HTTP-запросов. Повтор
 * возможен, пока прогон «ранний»: не больше одного завершённого шага, не больше
 * AI_RETRY_MAX_SHOWN_CHARS показанных символов и только read-only инструменты —
 * иначе ответ начался бы заново на глазах у пользователя (или повторил бы
 * запись в БД). Быстрые встроенные повторы AI SDK выключены
 * (maxRetries: 0): единственный источник повторов — цикл в orchestrator.ts,
 * и счётчик «попытка N из M» равен числу реальных запросов.
 */
export const AI_MAX_RETRIES = 3;

/** Пауза между повторами. Слот Gonka освобождается за десятки секунд. */
export const AI_RETRY_DELAY_MS = 20_000;

/**
 * Потолок паузы, когда провайдер прислал Retry-After больше настроенной:
 * ждём столько, сколько просит, но не дольше этого.
 */
export const AI_RETRY_DELAY_CAP_MS = 120_000;

/**
 * Одновременных прогонов чата к провайдеру на один процесс приложения.
 * Gonka держит слот за прерванным запросом, поэтому по умолчанию прогоны
 * сериализуются; остальные ждут в очереди с видимой позицией.
 * Очередь живёт в памяти процесса: при нескольких инстансах нужен внешний
 * брокер (см. docs/LIMITATIONS.md).
 */
export const AI_MAX_CONCURRENT_RUNS = 1;

/** Максимум ожидания в очереди; дальше — внятная ошибка, а не молчание. */
export const AI_QUEUE_TIMEOUT_MS = 180_000;

/**
 * Сколько уже показанного текста допустимо «перезапустить» повтором после
 * обрыва стрима. 300 символов — модель успела только объявить план
 * («Сначала посмотрю список сценариев…»); длиннее — пользователь уже читает
 * ответ, и перерисовка дороже, чем честная пометка об обрыве.
 */
export const AI_RETRY_MAX_SHOWN_CHARS = 300;

/**
 * Строка-маркер, с которой модель обязана начинать итоговый ответ.
 *
 * Reasoning-модели (MiniMax через Gonka) пишут ход рассуждений прямо в текст,
 * открывая `<think>` и НЕ закрывая его — по тегу границу «черновик/ответ» не
 * восстановить (из-за этого откатывали прошлую попытку скрыть рассуждения).
 * Поэтому границу задаём сами: всё до маркера считается черновиком, маркер в
 * ответ не попадает. Если маркера в шаге не оказалось, текст показывается
 * целиком — потерять ответ нельзя.
 *
 * Значение используется тремя местами сразу: промптом (system-prompt.ts),
 * фильтром потока (think-filter.ts) и тестами.
 */
export const AI_ANSWER_MARKER = "### Ответ";

/**
 * Сколько сырых чанков провайдера печатать в лог на каждом шаге
 * (переменная окружения AI_DEBUG_RAW_CHUNKS, 0 = выключено). Нужна, чтобы
 * увидеть фактический формат шлюза: приходит ли `<think>` внутри content или
 * у провайдера есть отдельное поле рассуждений.
 */
export const AI_DEBUG_RAW_CHUNK_MAX_CHARS = 600;
