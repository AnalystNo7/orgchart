/**
 * Бюджеты одного прогона AI-чата.
 *
 * Диагностика таймаута (tasks/ai-context-budget/BRIEF.md) показала: 99.8%
 * времени уходит в модель, и растёт оно вместе с объёмом входа. Поэтому
 * ограничиваем не код, а то, сколько данных попадает в контекст, и оставляем
 * запас, чтобы обрыв был внятным.
 */

/**
 * Держать синхронно с `export const maxDuration` в
 * src/app/api/ai/chat/route.ts: Next читает maxDuration статически, поэтому
 * импортированная константа там не годится — только литерал.
 */
export const AI_ROUTE_MAX_DURATION_SEC = 300;

/**
 * Запас, чтобы таймаут цикла generateText сработал ДО того, как платформа
 * убьёт функцию: успевают уйти SSE-событие error и сохранение диалога.
 */
export const AI_LOOP_SAFETY_MS = 20_000;

/**
 * Потолок суммарного объёма результатов инструментов за один прогон.
 * Результаты остаются в истории сообщений и переотправляются на каждом шаге,
 * поэтому важна именно сумма, а не размер отдельного вызова.
 * Наблюдавшийся провальный прогон набрал ~180 КБ за один шаг.
 */
export const AI_RUN_CONTEXT_BUDGET_BYTES = 120_000;

/**
 * Максимум шагов tool-цикла. До потолка по времени прогоны ни разу не доходили
 * до прежних 10 шагов, но пользователь явно просил не ограничиваться ими:
 * важен доведённый отчёт, а не экономия обращений.
 */
export const AI_MAX_STEPS = 30;

/** Бюджет ОДНОГО вызова модели (шага). Reasoning-шаги легально идут минутами. */
export const AI_STEP_TIMEOUT_MS = 600_000;

/**
 * Максимальная тишина между чанками стрима. Пока токены идут — не срабатывает
 * никогда; мёртвое соединение обрывается за 2 минуты вместо всего бюджета.
 */
export const AI_CHUNK_TIMEOUT_MS = 120_000;

/** Весь цикл, когда активного пресета нет (env-fallback). */
export const AI_DEFAULT_TOTAL_TIMEOUT_MS = 1_800_000;
